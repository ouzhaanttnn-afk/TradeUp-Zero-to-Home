import type {
  AttributeDefinition,
  EvidenceDefinition,
  Family,
  PreparationDefinition,
} from "../domain/models";

type Seed = Omit<
  Family,
  "attributes" | "evidence" | "defects" | "variants" | "preparation"
> & {
  attributeLabels: [string, string, string];
  evidenceLabels: [string, string];
};

const preparation = (base: number): PreparationDefinition[] => [
  {
    kind: "CLEAN",
    label: "Temizle",
    costMinor: Math.max(500, Math.round((base * 0.012) / 100) * 100),
    durationMin: 2,
    conditionGain: 4,
    confidenceGain: 0,
    valueGainBps: 180,
    liquidityGainBps: 250,
    maxUses: 1,
  },
  {
    kind: "TEST",
    label: "Test et",
    costMinor: Math.max(700, Math.round((base * 0.018) / 100) * 100),
    durationMin: 3,
    conditionGain: 0,
    confidenceGain: 0.24,
    valueGainBps: 0,
    liquidityGainBps: 350,
    maxUses: 1,
  },
  {
    kind: "COMPLETE",
    label: "Eksikleri tamamla",
    costMinor: Math.max(900, Math.round((base * 0.026) / 100) * 100),
    durationMin: 4,
    conditionGain: 1,
    confidenceGain: 0.06,
    valueGainBps: 300,
    liquidityGainBps: 500,
    maxUses: 1,
  },
];

const attribute = (label: string, index: number): AttributeDefinition => ({
  id: `attribute-${index}`,
  label,
  type: index === 1 ? "NUMBER" : index === 2 ? "BOOLEAN" : "CATEGORY",
  min: index === 1 ? 1 : undefined,
  max: index === 1 ? 100 : undefined,
  step: index === 1 ? 1 : undefined,
  options: index === 0 ? ["Temel", "Plus", "Pro"] : undefined,
  comparePriority: index + 1,
});

const evidence = (label: string, index: number): EvidenceDefinition => ({
  id: `evidence-${index}`,
  label,
  claim: `${label} satıcı beyanı`,
  checkedCopy: `${label} kontrol edildi`,
  inspectionKinds:
    index === 0 ? ["PHOTO", "ASK_SELLER"] : ["ASK_SELLER", "QUICK_TEST"],
  critical: index === 1,
});

const defineFamily = (seed: Seed): Family => {
  const evidenceDefinitions = seed.evidenceLabels.map(evidence);
  return {
    ...seed,
    attributes: seed.attributeLabels.map(attribute),
    evidence: evidenceDefinitions,
    defects: evidenceDefinitions.map((item, index) => ({
      id: `defect-${index}`,
      label: `${item.label} sorunu`,
      severity: index === 1 ? "HIGH" : "MEDIUM",
      valuePenaltyBps: index === 1 ? 1_600 : 800,
      riskSignal: index === 1 ? 0.7 : 0.4,
      evidenceId: item.id,
      overlayKey: index === 1 ? "warning" : "wear",
    })),
    variants: [
      { id: "standard", label: "Standart", valueFactorBps: 10_000 },
      { id: "premium", label: "Üst Paket", valueFactorBps: 11_500 },
    ],
    preparation: preparation(seed.baseValueMinor),
  };
};

